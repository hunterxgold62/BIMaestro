def highlight(t):
    img=base('Repérer les réseaux ciblés')
    d=ImageDraw.Draw(img)
    d.rounded_rectangle((30,73,610,301),radius=7,fill='white',outline='#9AABBE',width=3)
    for x in (215,425):d.line((x,73,x,301),fill='#CBD4DF',width=3)
    d.line((30,190,610,190),fill='#CBD4DF',width=3)
    for x,y in ((95,120),(280,230),(475,120),(515,235)):
        d.rectangle((x,y,x+55,y+28),fill='#E5EAF1',outline='#BBC7D5',width=2)
    parts=[[(65,160),(180,160),(180,250)],[(180,250),(370,250),(370,120)],[(370,120),(570,120)]]
    for i,points in enumerate(parts):
        selected=t>=.7+i*1.05
        if selected:
            d.line(points,fill='#C5DDFB',width=23,joint='curve')
        d.line(points,fill='#2378E1' if selected else '#8FA0B4',width=9,joint='curve')
    if t>4:
        for x,y in ((180,160),(370,250),(370,120)):
            r=int(14+5*math.sin(t*4))
            d.ellipse((x-r,y-r,x+r,y+r),outline='#2378E1',width=3)
    d.text((24,323),'Catégorie ciblée : canalisations',font=SMALL,fill='#65758A')
    return img

def cut(t):
    img=base('Révéler une traversée de paroi').convert('RGBA')
    d=ImageDraw.Draw(img)
    d.polygon([(65,257),(319,315),(575,225),(321,166)],fill='#E6ECF3')
    # Pipe behind the wall, then a wall with progressively lower opacity.
    d.line([(91,220),(525,129)],fill='#A45123',width=42)
    d.line([(91,212),(525,121)],fill='#ED8C43',width=31)
    wall=Image.new('RGBA',img.size)
    w=ImageDraw.Draw(wall)
    a=int(255-(min(max((t-1.2)/2.2,0),1)*205))
    w.polygon([(256,89),(388,119),(388,287),(256,257)],fill=(116,139,166,a),outline=(93,112,135,a))
    w.polygon([(256,89),(295,75),(427,105),(388,119)],fill=(172,188,207,a))
    w.polygon([(388,119),(427,105),(427,273),(388,287)],fill=(90,111,138,a))
    img=Image.alpha_composite(img,wall)
    d=ImageDraw.Draw(img)
    if t>2.4:
        r=int(20+4*math.sin(t*4))
        d.ellipse((335-r,168-r,335+r,168+r),outline='#E64B50',width=5)
        d.line((335,139,335,197),fill='#E64B50',width=2)
        d.line((306,168,364,168),fill='#E64B50',width=2)
    d.text((24,323),'Démonstration : transparence et intersection',font=SMALL,fill='#65758A')
    return img.convert('RGB')

def plan(after):
    img=Image.new('RGB',(640,360),BG);d=ImageDraw.Draw(img)
    rooms=[(35,85,240,205),(240,85,410,205),(410,85,605,205),(35,205,330,300),(330,205,605,300)]
    colors=['#D7EAFB','#DCEEDC','#F9E5C0','#E7DFF4','#D7EAFB']
    for i,r in enumerate(rooms):d.rectangle(r,fill=colors[i] if after else '#F1F1F1',outline='#52677F' if after else '#8A8A8A',width=4)
    for x,y in ((70,118),(277,124),(448,120),(90,232),(386,231)):
        d.rectangle((x,y,x+70,y+34),fill='#7D9EB8' if after else '#DBDBDB',outline='#52677F' if after else '#999999',width=2)
    d.line([(60,177),(367,177),(367,275),(570,275)],fill='#2378E1' if after else '#999999',width=8 if after else 3)
    return img
BEFORE,AFTER=plan(False),plan(True)
def wipe(t):
    hold=min(max((t-1)/3.6,0),1)
    x=int(35+570*hold)
    img=BEFORE.copy()
    img.paste(AFTER.crop((0,0,x,360)),(0,0))
    d=ImageDraw.Draw(img)
    d.rectangle((0,0,640,65),fill=BG)
    d.text((24,18),'Comparer les graphismes de la vue',font=BOLD,fill='#263548')
    d.line((x,77,x,308),fill='white',width=9)
    d.line((x,77,x,308),fill='#2378E1',width=3)
    d.ellipse((x-16,174,x+16,206),fill='#2378E1',outline='white',width=3)
    d.text((24,324),'APRÈS',font=SMALL,fill='#2378E1')
    d.text((520,324),'AVANT',font=SMALL,fill='#65758A')
    return img
